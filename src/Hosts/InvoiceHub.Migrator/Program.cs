using InvoiceHub.Audit;
using InvoiceHub.Billing;
using InvoiceHub.Compliance;
using InvoiceHub.Jobs;
using InvoiceHub.BuildingBlocks.Data;
using InvoiceHub.BuildingBlocks.Security;
using InvoiceHub.Events;
using InvoiceHub.Notifications;
using InvoiceHub.ServiceDefaults;
using InvoiceHub.Tenancy;
using InvoiceHub.Tenancy.Seeding;
using InvoiceHub.Webhooks;
using InvoiceHub.Webhooks.Seeding;
using Microsoft.Data.SqlClient;

// One-shot job started by the AppHost before any other process: applies the SQL scripts of every module,
// creates the application logins (api_user, worker_user) and seeds the demo tenants. Idempotent: safe to run on every start.
var builder = Host.CreateApplicationBuilder(args);
builder.AddServiceDefaults();

using var host = builder.Build();
var logger = host.Services.GetRequiredService<ILoggerFactory>().CreateLogger("Migrator");
var config = host.Services.GetRequiredService<IConfiguration>();

try
{
    var admin = Db.ConnectionString(config, DbRole.Admin, "InvoiceHub.Migrator");
    await WaitForSqlAsync(admin, logger);
    await EnsureFileSizesAsync(admin, logger);

    var runner = new SqlMigrationRunner(admin, host.Services.GetRequiredService<ILoggerFactory>().CreateLogger<SqlMigrationRunner>());
    await runner.ApplyAsync("platform", typeof(Db).Assembly);
    await runner.ApplyAsync(TenancyModule.ModuleName, typeof(TenancyModule).Assembly);
    await runner.ApplyAsync(EventsModule.ModuleName, typeof(EventsModule).Assembly);
    await runner.ApplyAsync(AuditModule.ModuleName, typeof(AuditModule).Assembly);
    await runner.ApplyAsync(NotificationsModule.ModuleName, typeof(NotificationsModule).Assembly);
    await runner.ApplyAsync(JobsModule.ModuleName, typeof(JobsModule).Assembly);
    await runner.ApplyAsync(ComplianceModule.ModuleName, typeof(ComplianceModule).Assembly);
    await runner.ApplyAsync(WebhooksModule.ModuleName, typeof(WebhooksModule).Assembly);
    await runner.ApplyAsync(BillingModule.ModuleName, typeof(BillingModule).Assembly);

    await EnsureLoginAsync(admin, "api_user", config["Db:Api:Password"], "api_role", logger);
    await EnsureLoginAsync(admin, "worker_user", config["Db:Worker:Password"], "worker_role", logger);

    await TenancySeeder.ApplyAsync(admin, logger);
    var masterKey = config["Secrets:MasterKey"] ?? throw new InvalidOperationException("Secrets:MasterKey is required (generated by the AppHost).");
    var otherReceivers = config.GetSection("Seed:Receivers").GetChildren().Where(c => !string.IsNullOrWhiteSpace(c.Value)).ToDictionary(c => c.Key, c => c.Value!);
    await WebhooksSeeder.ApplyAsync(admin, new AesGcmSecretProtector(masterKey), config["Seed:ReceiverBaseUrl"] ?? "http://localhost:5201", otherReceivers, logger);
    logger.LogInformation("Database is ready");
    return 0;
}
catch (Exception e)
{
    logger.LogCritical(e, "Migration failed");
    return 1;
}

/// <summary>
/// A database created with the defaults starts with 8 MB files that grow in small steps, and every growth pauses all writers while the new space is prepared. Under a burst of
/// events that shows up as a pause of seconds in the middle of the run (SQL Server in a container). The files are given room up front, and bigger growth steps, once.
/// Never shrinks and never touches a database that is already larger.
/// </summary>
static async Task EnsureFileSizesAsync(string connectionString, ILogger logger)
{
    await using var connection = new SqlConnection(connectionString);
    await connection.OpenAsync();
    await using var command = new SqlCommand("""
        DECLARE @sql nvarchar(max) = N'';
        SELECT @sql += N'ALTER DATABASE CURRENT MODIFY FILE (NAME = N''' + name + N''', SIZE = ' + CASE type WHEN 1 THEN N'256MB' ELSE N'512MB' END + N', FILEGROWTH = 128MB);'
        FROM sys.database_files
        WHERE (type = 0 AND size * 8 / 1024 < 512) OR (type = 1 AND size * 8 / 1024 < 256);
        IF LEN(@sql) > 0 EXEC sp_executesql @sql;
        """, connection) { CommandTimeout = 120 };
    await command.ExecuteNonQueryAsync();
    logger.LogInformation("Database files have room to grow without pausing writers");
}

static async Task WaitForSqlAsync(string connectionString, ILogger logger)
{
    for (var attempt = 1; attempt <= 30; attempt++)
    {
        try
        {
            await using var connection = new SqlConnection(connectionString);
            await connection.OpenAsync();
            return;
        }
        catch (SqlException) when (attempt < 30)
        {
            logger.LogInformation("SQL Server not ready yet (attempt {Attempt}/30)", attempt);
            await Task.Delay(TimeSpan.FromSeconds(2));
        }
    }
}

static async Task EnsureLoginAsync(string admin, string login, string? password, string role, ILogger logger)
{
    if (string.IsNullOrWhiteSpace(password) || !Regex.IsMatch(password, "^[A-Za-z0-9]{16,128}$"))
        throw new InvalidOperationException($"The password for {login} must be 16 to 128 letters or digits (it is generated by the AppHost).");

    await using var connection = new SqlConnection(admin);
    await connection.OpenAsync();
    // Login names and the password are validated above, so inlining them is safe (CREATE LOGIN cannot take parameters).
    var sql = $"""
        IF SUSER_ID(N'{login}') IS NULL CREATE LOGIN [{login}] WITH PASSWORD = N'{password}', CHECK_POLICY = OFF;
        ELSE ALTER LOGIN [{login}] WITH PASSWORD = N'{password}';
        IF DATABASE_PRINCIPAL_ID(N'{login}') IS NULL CREATE USER [{login}] FOR LOGIN [{login}];
        IF IS_ROLEMEMBER(N'{role}', N'{login}') IS NULL OR IS_ROLEMEMBER(N'{role}', N'{login}') = 0 ALTER ROLE [{role}] ADD MEMBER [{login}];
        """;
    await using var command = new SqlCommand(sql, connection);
    await command.ExecuteNonQueryAsync();
    logger.LogInformation("Login {Login} is ready in role {Role}", login, role);
}
